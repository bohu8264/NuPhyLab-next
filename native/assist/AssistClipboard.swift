struct AssistPrivacy {
    static let defaults = ["com.apple.Passwords","com.apple.keychainaccess","com.1password.1password","com.agilebits.onepassword7","com.bitwarden.desktop"]
    let excluded: Set<String>
    init(_ bundleIDs: [String]) {
        excluded = Set(bundleIDs.map { $0.lowercased() })
    }
    func allows(_ bundle: String?) -> Bool {
        guard let id = bundle?.lowercased(), !id.isEmpty else { return false }
        return !excluded.contains { id == $0 || id.hasPrefix($0 + ".") }
    }
    static let concealed = Set(["org.nspasteboard.ConcealedType","org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType","com.apple.is-remote-clipboard","de.petermaurer.TransientPasteboardType",
        "com.agilebits.onepassword","Pasteboard generator type"].map { NSPasteboard.PasteboardType($0) })
    static let origin = NSPasteboard.PasteboardType("org.nspasteboard.source")
}

enum AssistClipboard {
    struct FileReference: Codable {
        let path: String
        let bookmark: Data?
    }

    /// Reads only a newly observed change. Check every item's type and declared source before any payload.
    static func capture(_ board: NSPasteboard, change: Int, foreground: String, privacy: AssistPrivacy) -> (ClipContent,String)? {
        guard board.changeCount == change, privacy.allows(foreground),
              let items = board.pasteboardItems, !items.isEmpty, items.count <= 128,
              items.allSatisfy({ AssistPrivacy.concealed.isDisjoint(with:$0.types) }) else { return nil }
        let origins = items.filter { $0.types.contains(AssistPrivacy.origin) }.map { $0.string(forType:AssistPrivacy.origin) ?? "" }
        guard Set(origins).count <= 1, origins.allSatisfy(privacy.allows) else { return nil }
        let source = origins.first ?? foreground
        guard let content = read(items), board.changeCount == change else { return nil }
        return (content,source)
    }

    private static func read(_ items: [NSPasteboardItem]) -> ClipContent? {
        if items.contains(where:{ $0.types.contains(.fileURL) }) {
            guard items.allSatisfy({ $0.types.contains(.fileURL) }) else { return nil }
            let urls = items.compactMap { $0.string(forType:.fileURL).flatMap(URL.init(string:)) }
            guard urls.count == items.count, urls.allSatisfy({ $0.isFileURL && ($0.host ?? "localhost").isEmptyOrLocalHost }) else { return nil }
            let refs = urls.map { FileReference(path:$0.absoluteString,bookmark:try? PocketFileAccess.bookmark($0)) }
            guard let data = try? JSONEncoder().encode(refs) else { return nil }
            return ClipContent(kind:.files,text:urls.map(\.lastPathComponent).joined(separator:"\n"),data:data)
        }
        let strings = items.compactMap { item -> String? in
            let formats = item.types
            for type in [NSPasteboard.PasteboardType.string,.URL] where formats.contains(type) {
                if let value = item.string(forType:type) { return value }
            }
            if formats.contains(.rtf), let data = item.data(forType:.rtf), data.count <= ClipboardArchive.payloadLimit {
                return NSAttributedString(rtf:data,documentAttributes:nil)?.string
            }
            if formats.contains(.html), let html = item.string(forType:.html), html.utf8.count <= ClipboardArchive.textLimit {
                return PocketStore.plainTextFromHTML(html)
            }
            return nil
        }
        if strings.count == items.count {
            let text = strings.joined(separator:"\n")
            guard !text.isEmpty, text.utf8.count <= ClipboardArchive.textLimit else { return nil }
            var result = ClipContent(kind:PocketStore.isSupportedLink(text.trimmingCharacters(in:.whitespacesAndNewlines)) ? .link : .text,text:text)
            if items.count == 1, items[0].types.contains(.rtf), let rtf = items[0].data(forType:.rtf), rtf.count <= ClipboardArchive.payloadLimit {
                result.format = NSPasteboard.PasteboardType.rtf.rawValue; result.data = rtf
            }
            return result
        }
        guard items.count == 1, let type = items[0].availableType(from:[.png,.tiff,.init("public.jpeg"),.init("public.heic")]),
              let bytes = items[0].data(forType:type), bytes.count <= ClipboardArchive.payloadLimit,
              let src = CGImageSourceCreateWithData(bytes as CFData,[kCGImageSourceShouldCache:false] as CFDictionary),
              CGImageSourceGetCount(src) > 0 else { return nil }
        return ClipContent(kind:.image,text:"",format:type.rawValue,data:bytes)
    }

    static func thumbnail(_ bytes: Data, limit: Int) -> CGImage? {
        guard let src = CGImageSourceCreateWithData(bytes as CFData,[kCGImageSourceShouldCache:false] as CFDictionary) else { return nil }
        return CGImageSourceCreateThumbnailAtIndex(src,0,[kCGImageSourceCreateThumbnailFromImageAlways:true,
            kCGImageSourceCreateThumbnailWithTransform:true,kCGImageSourceThumbnailMaxPixelSize:limit] as CFDictionary)
    }
    static func png(_ image: CGImage) -> Data? { NSBitmapImageRep(cgImage:image).representation(using:.png,properties:[:]) }
    static func ocr(_ bytes: Data) async throws -> String {
        let request = VNRecognizeTextRequest()
        let worker = Task.detached(priority:.utility) {
            try Task.checkCancellation()
            guard let image = thumbnail(bytes,limit:2048) else { return "" }
            request.recognitionLevel = .accurate
            request.automaticallyDetectsLanguage = true
            try VNImageRequestHandler(cgImage:image).perform([request])
            try Task.checkCancellation()
            return String((request.results ?? []).compactMap { $0.topCandidates(1).first?.string }.joined(separator:"\n").prefix(20000))
        }
        return try await withTaskCancellationHandler { try await worker.value } onCancel: { worker.cancel(); request.cancel() }
    }
    static func attachment(_ bytes: Data) throws -> Data {
        if bytes.count <= AIRequestBuilder.maximumImageBytes { return bytes }
        guard let reduced = thumbnail(bytes,limit:1400), let data = png(reduced),
              data.count <= AIRequestBuilder.maximumImageBytes else { throw AIError.imageTooLarge }
        return data
    }
    static func write(_ content: ClipContent, to board: NSPasteboard, plain: Bool) throws {
        if !plain && content.kind == .files {
            let refs = try JSONDecoder().decode([FileReference].self,from:content.data)
            let urls = try refs.map { try PocketFileAccess.resolve($0.path,bookmark:$0.bookmark) }
            try PocketFileTransfer.write(urls,to:board)
            return
        }
        let item = NSPasteboardItem()
        if plain || content.kind != .image {
            guard !content.text.isEmpty else { throw AssistIssue("这条记录没有可粘贴的文字。","This entry contains no text to paste.") }
            item.setString(content.text,forType:.string)
            if !plain && content.kind == .link { item.setString(content.text,forType:.URL) }
        }
        if !plain && !content.format.isEmpty && !content.data.isEmpty {
            item.setData(content.data,forType:.init(content.format))
        }
        board.prepareForNewContents(with:.currentHostOnly)
        guard board.writeObjects([item]) else { throw AssistIssue("写入剪贴板失败。","Could not write to the clipboard.") }
    }
}
private extension String { var isEmptyOrLocalHost: Bool { isEmpty || lowercased() == "localhost" } }
