import AppKit

/// Reads a fresh selection only after a user-triggered Copy in the source app.
@MainActor final class CommandCopyHandoff {
    enum Outcome { case text(String), noText, tooLong, sourceLost }

    private let board: NSPasteboard
    private let activationCenter: NotificationCenter
    private let isCurrent: () -> Bool
    private let deliver: (Outcome) -> Void
    private var activation: NSObjectProtocol?
    private var readTask: Task<Void,Never>?
    private var deadline: Task<Void,Never>?
    private var active = false

    init(board: NSPasteboard = .general, activationCenter: NotificationCenter = NSWorkspace.shared.notificationCenter,
         isCurrent: @escaping () -> Bool, deliver: @escaping (Outcome) -> Void) {
        self.board = board
        self.activationCenter = activationCenter
        self.isCurrent = isCurrent
        self.deliver = deliver
    }

    func start(sourcePID: pid_t) {
        stop()
        active = true
        activation = activationCenter.addObserver(forName:NSWorkspace.didActivateApplicationNotification,object:nil,queue:.main) { [weak self] note in
            let app = note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication
            guard app?.processIdentifier != sourcePID else { return }
            MainActor.assumeIsolated { self?.finish(.sourceLost) }
        }
        guard isCurrent() else { finish(.sourceLost); return }
        deadline = Task { [weak self] in
            do { try await Task.sleep(nanoseconds:45_000_000_000) } catch { return }
            self?.finish(.sourceLost)
        }
    }

    func copyPressed() -> Bool {
        guard active else { return false }
        return receiveCopy(after:board.changeCount)
    }

    func receiveCopy(after baseline: Int) -> Bool {
        guard active else { return false }
        guard isCurrent() else { finish(.sourceLost); return false }
        readTask?.cancel()
        readTask = Task { [weak self] in
            // The app can finish copying before the shortcut's UI callback runs.
            for attempt in 0...40 {
                if attempt > 0 {
                    do { try await Task.sleep(nanoseconds:50_000_000) } catch { return }
                }
                guard let self, active, !Task.isCancelled else { return }
                guard isCurrent() else { finish(.sourceLost); return }
                let changed = board.changeCount
                guard changed != baseline, let items = board.pasteboardItems, !items.isEmpty else { continue }
                let outcome = Self.read(items)
                guard !Task.isCancelled, active, isCurrent(), board.changeCount == changed else {
                    if active && !Task.isCancelled { finish(.sourceLost) }
                    return
                }
                if case .text = outcome { finish(outcome) } else { deliver(outcome) }
                return
            }
            if let self, active { deliver(.noText) }
        }
        return true
    }

    private static func read(_ items: [NSPasteboardItem]) -> Outcome {
        let excluded: Set<NSPasteboard.PasteboardType> = [.fileURL, .init("NSFilenamesPboardType"),
            .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
            .init("org.nspasteboard.AutoGeneratedType"), .init("com.apple.is-remote-clipboard")]
        let originType = NSPasteboard.PasteboardType("org.nspasteboard.source")
        guard items.allSatisfy({ excluded.isDisjoint(with:$0.types) }) else { return .noText }
        for item in items where item.types.contains(originType) {
            guard CommandSelection.usesUserCopy(item.string(forType:originType)) else { return .noText }
        }
        var parts: [String] = []
        var bytes = 0
        for item in items {
            let value: String?
            if let plain = item.availableType(from:[.string,.init("NSStringPboardType")]) {
                value = item.string(forType:plain)
            } else if let rtf = item.data(forType:.rtf) {
                guard rtf.count <= 2_000_000 else { return .tooLong }
                value = NSAttributedString(rtf:rtf,documentAttributes:nil)?.string
            } else { return .noText }
            guard let value else { return .noText }
            bytes += value.utf8.count + (parts.isEmpty ? 0 : 1)
            guard bytes <= CommandSelection.maximumBytes else { return .tooLong }
            parts.append(value)
        }
        let text = parts.joined(separator:"\n")
        guard !text.trimmingCharacters(in:.whitespacesAndNewlines).isEmpty else { return .noText }
        return .text(text)
    }

    private func finish(_ outcome: Outcome) {
        guard active else { return }
        stop()
        deliver(outcome)
    }

    func stop() {
        active = false
        readTask?.cancel()
        readTask = nil
        deadline?.cancel()
        deadline = nil
        if let activation { activationCenter.removeObserver(activation) }
        activation = nil
    }
}
